package addon

import (
	"bytes"
	"maps"
	"path"
	"regexp"
	"slices"
	"strings"
)

// roles are each file's role to the agent (see Roles), by path: what the
// checks weigh a finding by, and the order Claude reads them in.
func roles(files map[string][]byte) map[string]string {
	instr, named := mentioned(files)
	out := map[string]string{}
	for p, b := range files {
		out[p] = role(p, b, instr, named)
	}
	return out
}

// mentioned are the instructions (SKILL.md, a spec, references/*.md, and
// the .md files SKILL.md names) and every file they name.
func mentioned(files map[string][]byte) (instr, named map[string]bool) {
	instr, named = map[string]bool{}, map[string]bool{}
	var queue []string
	for _, p := range slices.Sorted(maps.Keys(files)) {
		if p == "SKILL.md" || p == "spec" || strings.HasPrefix(p, "references/") && isMD(p) {
			instr[p] = true
			queue = append(queue, p)
		}
	}
	for len(queue) > 0 {
		d := queue[0]
		queue = queue[1:]
		for _, t := range pathWord.FindAllString(string(files[d]), -1) {
			t = strings.TrimRight(strings.TrimPrefix(strings.TrimPrefix(t, "<skill-dir>/"), "./"), ".:")
			for _, p := range []string{t, path.Join(path.Dir(d), t)} {
				if _, ok := files[p]; !ok || named[p] {
					continue
				}
				named[p] = true
				if d == "SKILL.md" && isMD(p) && !instr[p] && !licence(p) && !vendorPath(p) {
					instr[p] = true
					queue = append(queue, p)
				}
			}
		}
	}
	return instr, named
}

// pathWord is a word that may be a file's path ("bin/run.mjs",
// "../references/x.md").
var pathWord = regexp.MustCompile(`[\w.~/-]*\w\.\w+`)

// role is p's role: instr are the instructions, named the files they name.
func role(p string, b []byte, instr, named map[string]bool) string {
	ext := strings.ToLower(path.Ext(p))
	base := path.Base(p)
	switch {
	case instr[p]:
		return "instructions"
	case licence(p):
		return "license"
	case vendorPath(p) || generated(b) || lang(p, b) != "" && longLines(b):
		return "vendored"
	case lang(p, b) != "" && (named[p] || strings.HasPrefix(p, "bin/") || strings.HasPrefix(p, "scripts/")):
		return "script"
	case strings.HasPrefix(p, "assets/") || strings.Contains(p, "/assets/") || assetExt[ext] || strings.HasPrefix(base, "."):
		return "asset"
	case isMD(p) || ext == ".txt" || ext == ".rst" || strings.HasPrefix(p, "docs/") || strings.Contains(p, "/docs/") ||
		strings.HasPrefix(strings.ToUpper(base), "README") || strings.HasPrefix(strings.ToUpper(base), "CHANGELOG"):
		return "doc"
	case base != "package.json" && (ext == ".json" || ext == ".yaml" || ext == ".yml" || ext == ".toml" || ext == ".csv"):
		return "asset" // data
	}
	return "code"
}

var assetExt = map[string]bool{".png": true, ".jpg": true, ".jpeg": true, ".gif": true, ".webp": true, ".ico": true, ".svg": true,
	".woff": true, ".woff2": true, ".ttf": true, ".otf": true, ".eot": true, ".html": true, ".htm": true, ".css": true,
	".mp3": true, ".mp4": true, ".webm": true, ".wav": true, ".pdf": true}

func isMD(p string) bool {
	e := strings.ToLower(path.Ext(p))
	return e == ".md" || e == ".markdown" || e == ".mdx"
}

// licence: p is a licence or notice (LICENSE, NOTICE, COPYING, a font's
// OFL).
func licence(p string) bool {
	b := strings.ToUpper(path.Base(p))
	for _, s := range []string{"LICENSE", "LICENCE", "NOTICE", "COPYING"} {
		if strings.HasPrefix(b, s) {
			return true
		}
	}
	return strings.Contains(b, "NOTICES") || strings.HasSuffix(b, "-OFL.TXT") || strings.HasSuffix(b, "OFL.TXT")
}

// vendorPath: p is in a folder of others' code, or minified.
func vendorPath(p string) bool {
	for _, d := range strings.Split(path.Dir(p), "/") {
		switch d {
		case "vendor", "vendored", "node_modules", "third_party", "third-party", "bower_components":
			return true
		}
	}
	return strings.Contains(path.Base(p), ".min.")
}

// generated: b starts with a kept licence banner (/*!) or says it was
// generated.
func generated(b []byte) bool {
	head := b[:min(len(b), 512)]
	first, _, _ := bytes.Cut(head, []byte("\n"))
	return bytes.HasPrefix(bytes.TrimSpace(head), []byte("/*!")) ||
		bytes.Contains(first, []byte("Generated by")) || bytes.Contains(first, []byte("@generated")) || bytes.Contains(first, []byte("DO NOT EDIT"))
}

// longLines: b has a line no one writes by hand (minified, bundled).
func longLines(b []byte) bool {
	for len(b) > 0 {
		l, rest, _ := bytes.Cut(b, []byte("\n"))
		if len(l) > 3000 {
			return true
		}
		b = rest
	}
	return false
}

// own: a file of the add-on's own that it runs or reads as instructions.
func own(role string) bool { return role == "instructions" || role == "script" || role == "code" }
